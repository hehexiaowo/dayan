    /** 按编码取模板（找不到返回 null） */
    public static RefTemplate byCode(String code) {
        if (code == null || code.isBlank()) {
            return null;
        }
        return TEMPLATES.stream().filter(t -> t.code().equals(code)).findFirst().orElse(null);
    }
